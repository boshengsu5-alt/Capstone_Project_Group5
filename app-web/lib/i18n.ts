function resolvePath(source: unknown, path: string): unknown {
  return path.split('.').reduce<unknown>((current, key) => {
    if (current && typeof current === 'object' && key in (current as Record<string, unknown>)) {
      return (current as Record<string, unknown>)[key];
    }
    return undefined;
  }, source);
}

export function interpolate(template: string, params: TranslationParams = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => {
    const value = params[key];
    return value === undefined || value === null ? '' : String(value);
  });
}

export function getIntlLocale(locale: Locale): string {
  return locale === 'zh' ? 'zh-CN' : 'en-US';
}

export function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'zh';
  const value = window.localStorage.getItem('app-locale');
  return value === 'en' || value === 'zh' ? value : 'zh';
}

export function getTranslation(locale: Locale, path: string): string | undefined {
  const localized = resolvePath(translations[locale], path);
  if (typeof localized === 'string') return localized;

  const fallbackLocale = locale === 'en' ? 'zh' : 'en';
  const fallback = resolvePath(translations[fallbackLocale], path);
  return typeof fallback === 'string' ? fallback : undefined;
}

export function localizeCategoryName(
  category: { name?: string | null; name_zh?: string | null } | null | undefined,
  locale: Locale
): string {
  if (!category) return translations[locale].common.uncategorized;
  if (locale === 'zh') {
    return category.name_zh || category.name || translations.zh.common.uncategorized;
  }
  return category.name || category.name_zh || translations.en.common.uncategorized;
}

function translateByLookup(section: 'status' | 'condition' | 'roles' | 'warranty' | 'damageSeverity' | 'compensationStatus', value: string, t: Translator): string {
  const key = `${section}.${value}`;
  const result = t(key);
  return result === key ? value : result;
}

export function getStatusLabel(status: string, t: Translator): string {
  return translateByLookup('status', status, t);
}

export function getConditionLabel(condition: string, t: Translator): string {
  return translateByLookup('condition', condition, t);
}

export function getRoleLabel(role: string, t: Translator): string {
  return translateByLookup('roles', role, t);
}

export function getWarrantyLabel(warranty: string, t: Translator): string {
  return translateByLookup('warranty', warranty, t);
}

export function getDamageSeverityLabel(severity: string, t: Translator): string {
  return translateByLookup('damageSeverity', severity, t);
}

export function getCompensationStatusLabel(status: string, t: Translator): string {
  return translateByLookup('compensationStatus', status, t);
}

export function formatRelativeTime(value: string, locale: Locale): string {
  const diff = Date.now() - new Date(value).getTime();
  const mins = Math.floor(diff / 60000);
  const hours = Math.floor(diff / 3600000);
  const days = Math.floor(diff / 86400000);

  if (mins < 1) return translations[locale].notificationBell.justNow;
  if (mins < 60) return interpolate(translations[locale].notificationBell.minutesAgo, { count: mins });
  if (hours < 24) return interpolate(translations[locale].notificationBell.hoursAgo, { count: hours });
  return interpolate(translations[locale].notificationBell.daysAgo, { count: days });
}
